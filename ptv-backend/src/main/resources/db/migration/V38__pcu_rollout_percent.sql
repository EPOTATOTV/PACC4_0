-- V38: PCU 灰度发布（设计文档 §5.3）
-- 覆盖：t_release 增加 rollout_percent，表示该版本对外的灰度比例（0-100）。
--
-- 契约背景：端侧 GET /v1/update/check 过去只返回「最新已发布版本」。加上灰度之后，
-- 服务端要先按 pteid 分桶再决定这台设备够不够资格拿到新版本；不够资格时继续下发上一个
-- 已放量的版本，而不是告诉它「没有更新」——后者会让设备停在更旧的版本上。
--
-- 兼容性：生产 MySQL 8.0（utf8mb4 / InnoDB）；本地 H2（MODE=MySQL）同样执行。
--   默认 100 保证既有已发布版本行为完全不变（灰度是显式放量的事，不能靠迁移脚本悄悄限流）。
--   已合入的迁移脚本不可改，后续变更追加新版本号。
-- =====================================================================

ALTER TABLE t_release ADD COLUMN rollout_percent INT NOT NULL DEFAULT 100 COMMENT '灰度比例 0-100；100 表示全量';