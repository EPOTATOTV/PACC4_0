-- V39: 更新上报按「目标版本 + 时间」的统计索引（设计文档 §5.3）
-- 覆盖：t_update_report 增加 (to_version, created_at) 组合索引。
--
-- 契约背景：灰度放量按失败率自动暂停。判定发生在 GET /v1/update/check 上，即每次检查更新
-- 都要对某个目标版本做两次「时间窗内总数 / 失败数」的统计；该接口是无登录态公共接口，
-- 请求量随装机量线性增长，而 V37 只建了 (platform, created_at)，按 to_version 过滤用不上它。
-- 不补这条索引，灰度期间每次检查都是一次全表扫描。
--
-- 兼容性：生产 MySQL 8.0（utf8mb4 / InnoDB）；本地 H2（MODE=MySQL）同样执行。
--   纯新增索引，不改列、不影响既有查询计划以外的行为。已合入的迁移脚本不可改，
--   后续变更追加新版本号。
-- =====================================================================

CREATE INDEX idx_update_report_toversion_created ON t_update_report (to_version, created_at);